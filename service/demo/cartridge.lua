require "Wherigo"

local cartridge = Wherigo.ZCartridge()
cartridge.Id = "a2207986-2b70-4dd9-9c98-7aaaf02b5d61"
cartridge.Name = "Wherigo Compiler Demonstration"
cartridge.Description = "A small play-anywhere demonstration built with the open-source Wherigo Foundation compiler. Enter DEMO to finish."
cartridge.Author = "Wherigo website demonstration"
cartridge.Company = ""
cartridge.Activity = "Tour guide"
cartridge.Version = "1.0"
cartridge.StartingLocation = false
cartridge.StartingLocationDescription = "Play anywhere. No walking or GPS position is required."
cartridge.Media = false
cartridge.Icon = false

local task = Wherigo.ZTask(cartridge)
task.Name = "Try the compiled cartridge"
task.Description = "Enter DEMO when prompted to complete this demonstration."
task.Visible = true
task.Active = true
task.Complete = false

local prompt = Wherigo.ZInput(cartridge)
prompt.Name = "Compiler demonstration"
prompt.Text = "This cartridge was generated by WF.Compiler. Enter DEMO to complete the demonstration."
prompt.InputType = "Text"

function cartridge:OnStart()
    Wherigo.GetInput(prompt)
end

function prompt:OnGetInput(value)
    if value and string.upper(value) == "DEMO" then
        task.Complete = true
        cartridge.Complete = true
        Wherigo.MessageBox({Text = "Demonstration complete! The cartridge has run and handled your input.", Buttons = {"OK"}})
    else
        Wherigo.MessageBox({Text = "Enter DEMO to finish. You can reopen this cartridge to try again.", Buttons = {"OK"}})
    end
end

return cartridge
